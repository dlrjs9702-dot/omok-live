const cities = CITY_IDS.map((id) => {
  const c = CITIES[id];
  const [x, y] = NUDGE[id] || project(c.lat, c.lon);
  return { id, name: c.name, color: c.color, pop: c.population, x, y, links: [...c.links] };
});
const outlines = Object.fromEntries(Object.entries(OUTLINES).map(([name, pts]) => [name, 'M' + pts.map(([lon, lat]) => project(lat, lon).join(',')).join('L') + 'Z']));

