  assert.equal(dailyLine(1, { mine: { newHome: true, longAway: true } }, never).key, 'newHome');
  // the order: the contest, snow, the season -- at 35% (the usual line otherwise)
  const day = { contest: { phase: 'live', game: '두더지 잡기' }, snow: true, season: 'spring' };
  assert.equal(dailyLine(0, day, always).key, 'contestSoon'); assert.equal(dailyLine(0, day, never), null);
  assert.equal(dailyLine(0, { contest: { phase: 'done', winner: '하나' }, snow: true }, always).key, 'contestAfter');
  assert.equal(dailyLine(0, { snow: true, season: 'spring' }, always).key, 'snow'); assert.equal(dailyLine(0, { season: 'autumn' }, always).key, 'autumn');
  assert.equal(dailyLine(0, { season: 'winter' }, always), null); assert.equal(dailyLine(0, {}, always), null);
  // the words filled, the 조사 by the word's last sound ({x|이|가}), not the same line twice in a row
  assert.match(dailyLine(1, { contest: { phase: 'done', winner: '하나' } }, always).line, /^하나가 1등이라지/);
  assert.match(dailyLine(1, { contest: { phase: 'done', winner: '은빛' } }, always).line, /^은빛이 1등이라지/);
  const seq = (...v) => () => v.shift() ?? 0; // (the chance, then which line)
  assert.match(dailyLine(4, { contest: { phase: 'soon', game: '프리셀' } }, seq(0, 0.9)).line, /프리셀이라니 흥미롭네/);
  assert.match(dailyLine(4, { contest: { phase: 'soon', game: '반응속도' } }, seq(0, 0.9)).line, /반응속도라니 흥미롭네/);
  const first = dailyLine(0, { season: 'spring' }, always).raw; assert.notEqual(dailyLine(0, { season: 'spring', last: first }, always).raw, first);
  assert.ok(!/[{}]/.test(dailyLine(4, { mine: { longAway: true }, me: '솔' }, always).line)); assert.match(dailyLine(4, { mine: { longAway: true }, me: '솔' }, always).line, /솔아/);
