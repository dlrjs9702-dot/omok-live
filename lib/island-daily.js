const MINE = Object.freeze(['bigCatch', 'newHome', 'trophy', 'longAway']); // (said once a day to each islander, first)
const CHANCE = 0.35; // (the day's things: now and then -- the islander's usual lines otherwise)
const SEASONS = Object.freeze(['spring', 'summer', 'autumn']); // (winter: the islanders' winter mood, as before)

// the day's line of islander n, or null (their usual line then): ctx { told: a line of mine said to them today, mine: { bigCatch,
// newHome, trophy, longAway } (booleans), contest: { phase, game, winner }, snow, season, me, last: the line they said last
// to me (not twice in a row) } -> { key, mine, line }
function dailyLine(n, ctx = {}, random = Math.random) {
  const d = DAILY[n]; if (!d) return null;
  let key = !ctx.told ? MINE.find((k) => ctx.mine?.[k]) : null; const mine = Boolean(key);
  if (!key) {
    const k = ctx.contest;
    key = ['soon', 'live'].includes(k?.phase) && k.game ? 'contestSoon' : k?.winner ? 'contestAfter' : ctx.snow ? 'snow' : SEASONS.includes(ctx.season) ? ctx.season : null;
    if (!key || random() >= CHANCE) return null;
  }
  const lines = d[key].filter((l) => l !== ctx.last); const raw = lines[Math.floor(random() * lines.length) % lines.length] || d[key][0];
  const vars = { me: ctx.me || '친구', game: ctx.contest?.game || '', winner: ctx.contest?.winner || '' };
  const line = Object.entries(vars).reduce((s, [name, word]) => Cast.slot(s, name, word), raw);
  return { key, mine, line: Cast.withTail(line, n), raw };
}

